import java.util.*;
public class Odd_Even_using_if_else_LOOP {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        int x= sc.nextInt();

        if(x%2==0){
            System.out.println("EVEN");           
        }else{
            System.out.println("ODD");
        }

    }    
}  
